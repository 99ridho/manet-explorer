    'def discover(net, src, dst):',
    '    heard, replies = [(src, [src])], []',
    '    src.seen = True',
    '    while heard or replies:',
    '        for rrep in list(replies):',
    '            rrep.hop()  # one hop toward src per tick',
    '            if rrep.at == src:',
    '                replies.remove(rrep)',
    '                src.routes.append(rrep.route)  # every route is kept, in order of arrival',
    '        sending, heard = heard, []',
    '        for v, record in sending:',
    '            if v.black_hole:',
    '                continue  # a black hole never passes the RREQ on',
    '            v.broadcast(RREQ(record))',
    '            for n in v.neighbors():',
    '                if n != dst and n.seen:',
    '                    continue  # drop the duplicate copy',
    '                n.seen = True',
    '                if n == dst:',
    '                    replies.append(RREP(record + [dst]))  # dst answers every copy',
    '                    continue',
    '                heard.append((n, record + [n]))',
    '                if n.black_hole:',
    '                    replies.append(RREP(record + [n, dst]))  # a route n does not have',
    '                if n.tunnel_end and not n.far_end.seen:',
    '                    n.far_end.seen = True',
